function renderPlayers(role = "all") {

    const grid =
        document.getElementById("playersGrid");

    grid.innerHTML = "";

    const filteredPlayers =
        role === "all"
            ? players
            : players.filter(player =>
                player.role === role
            );

    filteredPlayers.forEach(player => {

        const initials =
            player.name
                .split(" ")
                .map(word => word[0])
                .join("")
                .substring(0, 2);

        grid.innerHTML += `

            <article
                class="player-card"
                data-role="${player.role}"
            >

                <div class="player-number">
                    ${player.number}
                </div>

                <div class="player-avatar">
                    ${initials}
                </div>

                <h3>
                    ${player.name}
                </h3>

                <p class="player-role">
                    ${player.role}
                </p>

            </article>

        `;
    });
}


