function formatDate(dateString) {

    const date =
        new Date(dateString);

    return date.toLocaleDateString(
        "it-IT",
        {
            day: "2-digit",
            month: "long",
            year: "numeric"
        }
    );
}


function formatTime(dateString) {

    const date =
        new Date(dateString);

    return date.toLocaleTimeString(
        "it-IT",
        {
            hour: "2-digit",
            minute: "2-digit"
        }
    );
}




function renderMatches(filter = "all") {

    const list =
        document.getElementById("matchesList");

    list.innerHTML = "";

    const now = new Date();

    const filteredMatches =
        matches.filter(match => {

            const date =
                new Date(match.date);

            if (filter === "upcoming") {
                return date > now && !match.score;
            }

            if (filter === "played") {
                return match.score !== null;
            }

            if (filter === "home") {
                return match.home === "Sorisolese";
            }

            if (filter === "away") {
                return match.away === "Sorisolese";
            }

            return true;
        });

    filteredMatches.forEach(match => {

        const score =
            match.score
                ? `${match.score.home} - ${match.score.away}`
                : "VS";

        list.innerHTML += `

            <article class="match-row">

                <div class="match-day">
                    GIORNATA ${match.round}
                </div>

                <div class="match-home">
                    <img
                        src="${logos[match.home]}"
                        alt="${match.home}"
                    >

                    <span>
                        ${match.home}
                    </span>
                </div>

                <div class="match-score">
                    ${score}
                </div>

                <div class="match-away">
                    <span>
                        ${match.away}
                    </span>

                    <img
                        src="${logos[match.away]}"
                        alt="${match.away}"
                    >
                </div>

                <div class="match-date">
                    ${formatDate(match.date)}<br>
                    ${formatTime(match.date)}
                </div>

            </article>

        `;
    });
}




