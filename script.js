function updateNextMatch() {

    const now =
        new Date();

    const next =
        matches.find(match =>
            new Date(match.date) > now &&
            match.score === null
        );

    if (!next) {

        document
            .getElementById("nextMatchDate")
            .textContent =
            "NESSUNA PARTITA PROGRAMMATA";

        return;
    }

    document
        .getElementById("nextMatchDate")
        .textContent =
        formatDate(next.date);

    document
        .getElementById("nextMatchTime")
        .textContent =
        `ORE ${formatTime(next.date)}`;

    document
        .getElementById("homeTeam")
        .textContent =
        next.home;

    document
        .getElementById("awayTeam")
        .textContent =
        next.away;

    document
        .getElementById("homeLogo")
        .src =
        logos[next.home];

    document
        .getElementById("awayLogo")
        .src =
        logos[next.away];


    function updateCountdown() {

        const difference =
            new Date(next.date) -
            new Date();

        if (difference <= 0) {

            document
                .getElementById("countdown")
                .textContent =
                "INIZIO PARTITA";

            return;
        }

        const days =
            Math.floor(
                difference / (1000 * 60 * 60 * 24)
            );

        const hours =
            Math.floor(
                (difference / (1000 * 60 * 60)) % 24
            );

        const minutes =
            Math.floor(
                (difference / (1000 * 60)) % 60
            );

        document
            .getElementById("countdown")
            .textContent =
            `${days}G ${hours}H ${minutes}M`;
    }

    updateCountdown();

    setInterval(
        updateCountdown,
        60000
    );
}




function updateLiveStatus() {

    const now =
        new Date();

    const day =
        now.getDay();

    const hours =
        now.getHours();

    const minutes =
        now.getMinutes();

    const totalMinutes =
        hours * 60 + minutes;

    const text =
        document.getElementById("liveText");

    const label =
        document.getElementById("liveLabel");

    const dot =
        document.getElementById("liveDot");


   

    const trainingDays = [2, 4];

    const trainingStart =
        19 * 60;

    const trainingEnd =
        21 * 60;


  

    const currentMatch =
        matches.find(match => {

            const start =
                new Date(match.date);

            const end =
                new Date(
                    start.getTime() +
                    2 * 60 * 60 * 1000
                );

            return now >= start &&
                   now <= end;
        });


    if (currentMatch) {

        label.textContent =
            "LIVE";

        text.textContent =
            `PARTITA IN CORSO • ${currentMatch.home} VS ${currentMatch.away}`;

        label.style.color =
            "#ff3b4d";

        dot.style.background =
            "#ff3b4d";

        dot.style.boxShadow =
            "0 0 12px #ff3b4d";

        return;
    }


    if (
        trainingDays.includes(day) &&
        totalMinutes >= trainingStart &&
        totalMinutes <= trainingEnd
    ) {

        label.textContent =
            "LIVE";

        text.textContent =
            "LA SQUADRA SI STA ALLENANDO";

        label.style.color =
            "#18d26e";

        dot.style.background =
            "#18d26e";

        dot.style.boxShadow =
            "0 0 12px #18d26e";

        return;
    }


    label.textContent =
        "STATO";

    text.textContent =
        "SQUADRA ATTUALMENTE NON IN ATTIVITÀ";

    label.style.color =
        "#9ba9b7";

    dot.style.background =
        "#9ba9b7";

    dot.style.boxShadow =
        "none";
}




